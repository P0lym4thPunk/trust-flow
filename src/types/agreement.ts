export type TransactionType = "WORK" | "PROTECTED_PAYMENT" | "CONDITIONAL_DISBURSEMENT";

export type EscrowStatus =
  | "DRAFT"
  | "CREATED"
  | "READY_FOR_FUNDING"
  | "FUNDING_PENDING"
  | "FUNDED"
  | "FULFILMENT_SUBMITTED"
  | "APPROVED"
  | "RELEASED"
  | "REFUNDED"
  | "CANCELLED";

export type CancelRequestState = "NONE" | "REQUESTED_BY_PAYER" | "REQUESTED_BY_RECIPIENT";

export type AssetSymbol = "XLM" | "USDC";

export interface Participant {
  address: string;
  role: "PAYER" | "RECIPIENT" | "APPROVER";
  displayName: string;
  accepted: boolean;
  acceptedAt?: string;
  acceptedHash?: string;
}

export interface AgreementCondition {
  type: "APPROVAL";
  description: string;
  approverAddress: string;
}

export interface AgreementTerms {
  amount: string; // Validated decimal string, max 7 decimals, e.g. "500.00"
  asset: AssetSymbol;
  payer: string;
  recipient: string;
  approver: string;
  title: string;
  description: string;
  deliverables: string[];
  condition: string;
  cancellationTerms: string;
  deadline: string; // ISO-8601 string or Unix timestamp seconds
  contractId: string;
  domain: string;
  network: string;
  version: number;
}

export interface ActivityEvent {
  id: string;
  agreementId: string;
  timestamp: string;
  actor: string;
  actorRole: "PAYER" | "RECIPIENT" | "APPROVER" | "SYSTEM";
  type:
    | "CREATED"
    | "ACCEPTED"
    | "FUNDED"
    | "FULFILMENT_SUBMITTED"
    | "APPROVED"
    | "REJECTED"
    | "RELEASED"
    | "REFUNDED"
    | "CANCEL_REQUESTED"
    | "CANCEL_CONFIRMED"
    | "CANCELLED";
  title: string;
  description: string;
  txHash?: string;
}

export interface AgreementRecord {
  id: string;
  escrowId?: number; // Monotonic on-chain ID generated by contract
  transactionType: TransactionType;
  title: string;
  description: string;
  terms: AgreementTerms;
  canonicalHash: string;
  version: number;
  status: EscrowStatus;
  cancelRequest: CancelRequestState;
  payerAccepted: boolean;
  recipientAccepted: boolean;
  fulfilmentHash?: string;
  fulfilmentNotes?: string;
  fulfilmentEvidenceUrl?: string;
  rejectionReasonHash?: string;
  rejectionReason?: string;
  fundingTxHash?: string;
  releaseTxHash?: string;
  refundTxHash?: string;
  createdAt: string;
  updatedAt: string;
  fundedAt?: string;
  completedAt?: string;
  activity: ActivityEvent[];
}

export interface CheckerFinding {
  severity: "BLOCKING" | "WARNING" | "SUGGESTION";
  field: string;
  issue: string;
  whyItMatters: string;
  suggestedRevision: string;
}

export interface CheckerAuditResult {
  overallStatus: "PASS" | "NEEDS_REVISION" | "BLOCKING_ISSUES";
  findings: CheckerFinding[];
  summary: string;
}
